<article class="sc-prose">
    <h1>Help Center</h1>
    <h2>Why isn't my note visible yet?</h2>
    <p>Every upload is reviewed first. You will get a notification when it is approved or rejected, and you can check its status in your Personal study space.</p>
    <h2>Which files can I upload?</h2>
    <p>PDF, DOCX and PPTX files, up to 10 MB each.</p>
    <h2>I didn't get my verification email</h2>
    <p>Check your junk folder, then sign in again to reach the "Check your inbox" page, where you can resend the link.</p>
    <h2>I forgot my password</h2>
    <p>Use <a href="<?= e(url("/forgot-password")) ?>">Forgot password</a> on the sign-in page and we will email you a reset link.</p>
    <h2>What can I share in the forum and study groups?</h2>
    <p>JPG, PNG, GIF and WEBP images up to 5 MB, and PDF, DOCX, PPTX, XLSX and TXT files up to 10 MB, with up to 4 in one post. Programs, ZIP files, and documents with macros or scripts are refused. We check every file's contents, but still only open files from people you trust.</p>
    <h2>How do I report something?</h2>
    <p>Use the Report button on any note, question, answer or comment. A moderator will review it.</p>
    <h2>Why can't I see notes from other faculties?</h2>
    <p>Notes, the forum, study groups and meetings only show your own faculty, so everything you see is relevant to you. If your faculty is wrong, ask an admin to change it.</p>
    <h2>How do I work with students from other faculties?</h2>
    <p>Use Find Members. Post a request or respond to one. When a request's author accepts your response, you can both see each other's university email.</p>
    <h2>How do I arrange a group meeting?</h2>
    <p>Open your study group and choose Schedule meeting. Pick online, physical or hybrid, then add the date, time, and room or link. Members are notified and can answer Going or Can't go.</p>
    <h2>How does the weekly goal work?</h2>
    <p>Log your study time in your Personal study space. Your goal and streak update from what you log.</p>
</article>
