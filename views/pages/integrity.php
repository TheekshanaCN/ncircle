<article class="sc-prose">
    <h1>Academic Integrity &amp; Honor Code</h1>
    <p>Ncircle supports cooperative study and ethical learning, in line with NSBM intellectual property standards and plagiarism guidelines.</p>
    <h2>The Honor Code</h2>
    <ul>
        <li>Share your own work, and credit the sources you used.</li>
        <li>Use shared notes to learn, not to copy into your own submissions.</li>
        <li>Never post answers to an exam or assignment that is still open.</li>
        <li>Respect lecturers' copyright on slides and past papers.</li>
    </ul>
    <h2 id="moderation">How moderation works</h2>
    <ol>
        <li><strong>Upload.</strong> You submit a note with its module code.</li>
        <li><strong>Review.</strong> An admin checks formatting, academic ethics, citation accuracy and legibility, then approves or rejects it with a reason.</li>
        <li><strong>Exchange.</strong> Approved notes go live. Anyone can report a problem, and moderators review each report.</li>
    </ol>
